#pragma once

namespace sft {
struct IWriter {
  virtual ~IWriter() = default;

  virtual void beginObject(std::string_view name) = 0;

  virtual void endObject() = 0;

  virtual void beginArray(std::string_view name, size_t count) = 0;

  virtual void endArray() = 0;

  virtual void write(std::string_view name, bool v) = 0;

  virtual void write(std::string_view name, char v) = 0;

  virtual void write(std::string_view name, int8_t v) = 0;

  virtual void write(std::string_view name, int16_t v) = 0;

  virtual void write(std::string_view name, int32_t v) = 0;

  virtual void write(std::string_view name, int64_t v) = 0;

  virtual void write(std::string_view name, uint8_t v) = 0;

  virtual void write(std::string_view name, uint16_t v) = 0;

  virtual void write(std::string_view name, uint32_t v) = 0;

  virtual void write(std::string_view name, uint64_t v) = 0;

  virtual void write(std::string_view name, float v) = 0;

  virtual void write(std::string_view name, double v) = 0;

  virtual void write(std::string_view name, std::string_view v) = 0;
};

struct IReader {
  virtual ~IReader() = default;

  virtual void beginObject(std::string_view name) = 0;

  virtual void endObject() = 0;

  virtual void beginArray(std::string_view name, size_t& count) = 0;

  virtual void endArray() = 0;

  virtual auto hasKey(std::string_view name) -> bool = 0;

  virtual void read(std::string_view name, bool& v) = 0;

  virtual void read(std::string_view name, char& v) = 0;

  virtual void read(std::string_view name, int8_t& v) = 0;

  virtual void read(std::string_view name, int16_t& v) = 0;

  virtual void read(std::string_view name, int32_t& v) = 0;

  virtual void read(std::string_view name, int64_t& v) = 0;

  virtual void read(std::string_view name, uint8_t& v) = 0;

  virtual void read(std::string_view name, uint16_t& v) = 0;

  virtual void read(std::string_view name, uint32_t& v) = 0;

  virtual void read(std::string_view name, uint64_t& v) = 0;

  virtual void read(std::string_view name, float& v) = 0;

  virtual void read(std::string_view name, double& v) = 0;

  virtual void read(std::string_view name, std::string& v) = 0;
};

namespace detail {
/// @brief Checks if the type T has a write method on IWriter
template <class T>
concept IsSimpleSerializable = requires(T t, std::string_view name, IWriter& writer) {
  { writer.write(name, t) };
};

/// @brief Checks if the type T has a read method on IReader
template <class T>
concept IsSimpleDeserializable = requires(T& t, std::string_view name, IReader& reader) {
  { reader.read(name, t) };
};
} // namespace detail

//=============================================================================
// Forward declarations of generic serialize methods
//=============================================================================

template <detail::IsSimpleSerializable T>
void serialize(IWriter& writer, std::string_view name, T const& v);

template <wx::detail::HasReflectionMembers T>
void serialize(IWriter& writer, std::string_view name, T const& v);

template <class T, class A>
void serialize(IWriter& writer, std::string_view name, std::vector<T, A> const& v);

template <class T>
void serialize(IWriter& writer, std::string_view name, std::optional<T> const& v);

//=============================================================================
// Forward declarations of generic deserialize methods
//=============================================================================

/// @brief Deserializes simple types that can be read directly from IReader
template <detail::IsSimpleDeserializable T>
void deserialize(IReader& reader, std::string_view name, T& v);

/// @brief Deserializes objects that have reflection members.
template <wx::detail::HasReflectionMembers T>
void deserialize(IReader& reader, std::string_view name, T& v);

/// @brief Deserializes vectors of objects
template <class T, class A>
void deserialize(IReader& reader, std::string_view name, std::vector<T, A>& v);

/// @brief Deserializes optional values.
template <class T>
void deserialize(IReader& reader, std::string_view name, std::optional<T>& v);

} // namespace sft

#include "serialization/detail/deserialize.inl"
#include "serialization/detail/serialize.inl"
