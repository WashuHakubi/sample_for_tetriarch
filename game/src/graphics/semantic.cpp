uint32_t getPitch(SDL_GPUVertexElementFormat format) {
  switch (format) {
    case SDL_GPU_VERTEXELEMENTFORMAT_INT:
      return sizeof(int32_t);
    case SDL_GPU_VERTEXELEMENTFORMAT_INT2:
      return sizeof(int32_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_INT3:
      return sizeof(int32_t) * 3;
    case SDL_GPU_VERTEXELEMENTFORMAT_INT4:
      return sizeof(int32_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_UINT:
      return sizeof(uint32_t);
    case SDL_GPU_VERTEXELEMENTFORMAT_UINT2:
      return sizeof(uint32_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_UINT3:
      return sizeof(uint32_t) * 3;
    case SDL_GPU_VERTEXELEMENTFORMAT_UINT4:
      return sizeof(uint32_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_FLOAT:
      return sizeof(float);
    case SDL_GPU_VERTEXELEMENTFORMAT_FLOAT2:
      return sizeof(float) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_FLOAT3:
      return sizeof(float) * 3;
    case SDL_GPU_VERTEXELEMENTFORMAT_FLOAT4:
      return sizeof(float) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_BYTE2:
      return sizeof(int8_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_BYTE4:
      return sizeof(int8_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_UBYTE2:
      return sizeof(uint8_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_UBYTE4:
      return sizeof(uint8_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_BYTE2_NORM:
      return sizeof(int8_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_BYTE4_NORM:
      return sizeof(int8_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_UBYTE2_NORM:
      return sizeof(uint8_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_UBYTE4_NORM:
      return sizeof(uint8_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_SHORT2:
      return sizeof(int16_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_SHORT4:
      return sizeof(int16_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_USHORT2:
      return sizeof(uint16_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_USHORT4:
      return sizeof(uint16_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_SHORT2_NORM:
      return sizeof(int16_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_SHORT4_NORM:
      return sizeof(int16_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_USHORT2_NORM:
      return sizeof(uint16_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_USHORT4_NORM:
      return sizeof(uint16_t) * 4;
    case SDL_GPU_VERTEXELEMENTFORMAT_HALF2:
      return sizeof(uint16_t) * 2;
    case SDL_GPU_VERTEXELEMENTFORMAT_HALF4:
      return sizeof(uint16_t) * 4;
    default:
      throw std::runtime_error("Unknown vertex format");
  }
}

bool fromString(std::string_view value, Semantic& out) {
  static std::unordered_map<std::string_view, Semantic> const semantics = {
      {"POSITION", Semantic::Position},    {"NORMAL", Semantic::Normal},        {"TANGENT", Semantic::Tangent},

      {"TEXCOORD0", Semantic::TexCoord0},  {"TEXCOORD1", Semantic::TexCoord1},  {"TEXCOORD2", Semantic::TexCoord2},
      {"TEXCOORD3", Semantic::TexCoord3},

      {"TEXCOORD_0", Semantic::TexCoord0}, {"TEXCOORD_1", Semantic::TexCoord1}, {"TEXCOORD_2", Semantic::TexCoord2},
      {"TEXCOORD_3", Semantic::TexCoord3},

      {"COLOR0", Semantic::Color0},        {"COLOR1", Semantic::Color1},        {"COLOR2", Semantic::Color2},
      {"COLOR3", Semantic::Color3},

      {"COLOR_0", Semantic::Color0},       {"COLOR_1", Semantic::Color1},       {"COLOR_2", Semantic::Color2},
      {"COLOR_3", Semantic::Color3},

      {"JOINT0", Semantic::Joints0},       {"JOINT1", Semantic::Joints1},       {"JOINT2", Semantic::Joints2},
      {"JOINT3", Semantic::Joints3},

      {"JOINTS_0", Semantic::Joints0},     {"JOINTS_1", Semantic::Joints1},     {"JOINTS_2", Semantic::Joints2},
      {"JOINTS_3", Semantic::Joints3},

      {"WEIGHTS0", Semantic::Weights0},    {"WEIGHTS1", Semantic::Weights1},    {"WEIGHTS2", Semantic::Weights2},
      {"WEIGHTS3", Semantic::Weights3},

      {"WEIGHTS_0", Semantic::Weights0},   {"WEIGHTS_1", Semantic::Weights1},   {"WEIGHTS_2", Semantic::Weights2},
      {"WEIGHTS_3", Semantic::Weights3},
  };

  if (auto const it = semantics.find(value); it != semantics.end()) {
    out = it->second;
    return true;
  }

  out = Semantic::Invalid;
  return false;
}

std::string_view toString(Semantic semantic) {
  switch (semantic) {
    case Semantic::Position:
      return "POSITION";
    case Semantic::Normal:
      return "NORMAL";
    case Semantic::Tangent:
      return "TANGENT";
    case Semantic::TexCoord0:
      return "TEXCOORD0";
    case Semantic::TexCoord1:
      return "TEXCOORD1";
    case Semantic::TexCoord2:
      return "TEXCOORD2";
    case Semantic::TexCoord3:
      return "TEXCOORD3";
    case Semantic::Color0:
      return "COLOR0";
    case Semantic::Color1:
      return "COLOR1";
    case Semantic::Color2:
      return "COLOR2";
    case Semantic::Color3:
      return "COLOR3";
    case Semantic::Joints0:
      return "JOINTS0";
    case Semantic::Joints1:
      return "JOINTS1";
    case Semantic::Joints2:
      return "JOINTS2";
    case Semantic::Joints3:
      return "JOINTS3";
    case Semantic::Weights0:
      return "WEIGHTS0";
    case Semantic::Weights1:
      return "WEIGHTS1";
    case Semantic::Weights2:
      return "WEIGHTS2";
    case Semantic::Weights3:
      return "WEIGHTS3";
    default:
      return "INVALID";
  }
}

void serialize(IWriter& writer, std::string_view name, Semantic const& semantic) {
  writer.write(name, toString(semantic));
}

void deserialize(IReader& reader, std::string_view name, Semantic& semantic) {
  std::string value;
  reader.read(name, value);

  // Strip off any prefix to get to the bare semantic
  if (name.starts_with("in.var.")) {
    name = name.substr(7);
  } else if (name.starts_with("out.var.")) {
    name = name.substr(8);
  }

  if (!fromString(value, semantic)) {
    throw std::runtime_error(std::format("Unsupported semantic name: {}", value));
  }
}

void deserialize(IReader& reader, std::string_view name, SDL_GPUVertexElementFormat& format) {
  static const std::unordered_map<std::string, SDL_GPUVertexElementFormat> name_to_format{
      {"float", SDL_GPU_VERTEXELEMENTFORMAT_FLOAT},
      {"float2", SDL_GPU_VERTEXELEMENTFORMAT_FLOAT2},
      {"float3", SDL_GPU_VERTEXELEMENTFORMAT_FLOAT3},
      {"float4", SDL_GPU_VERTEXELEMENTFORMAT_FLOAT4},

      {"int", SDL_GPU_VERTEXELEMENTFORMAT_INT},
      {"int2", SDL_GPU_VERTEXELEMENTFORMAT_INT2},
      {"int3", SDL_GPU_VERTEXELEMENTFORMAT_INT3},
      {"int4", SDL_GPU_VERTEXELEMENTFORMAT_INT4},

      {"byte2", SDL_GPU_VERTEXELEMENTFORMAT_BYTE2},
      {"byte4", SDL_GPU_VERTEXELEMENTFORMAT_BYTE4},

      {"ubyte2", SDL_GPU_VERTEXELEMENTFORMAT_UBYTE2},
      {"ubyte4", SDL_GPU_VERTEXELEMENTFORMAT_UBYTE4},

      {"short2", SDL_GPU_VERTEXELEMENTFORMAT_SHORT2},
      {"short4", SDL_GPU_VERTEXELEMENTFORMAT_SHORT4},

      {"ushort2", SDL_GPU_VERTEXELEMENTFORMAT_USHORT2},
      {"ushort4", SDL_GPU_VERTEXELEMENTFORMAT_USHORT4},

      {"half2", SDL_GPU_VERTEXELEMENTFORMAT_HALF2},
      {"half4", SDL_GPU_VERTEXELEMENTFORMAT_HALF4},
  };

  std::string value;
  reader.read(name, value);
  if (auto it = name_to_format.find(value); it != name_to_format.end()) {
    format = it->second;
  }

  throw std::runtime_error(std::format("Unsupported format: {}", value));
}

