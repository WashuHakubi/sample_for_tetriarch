#include "graphics/gltf.h"

namespace sft {
void gltf::Primitive::getDrawData(
    Material const& material,
    std::vector<SDL_GPUBufferBinding>& vertex_bindings,
    SDL_GPUBufferBinding& index_binding,
    SDL_GPUIndexElementSize& element_size,
    uint32_t& index_count) {
  auto inputs = material.getVertexInputs();

  for (auto&& input : inputs) {
    auto attr_it = std::ranges::find(attributes_, input.name, [](auto const& attr) { return attr.name; });

    if (attr_it == attributes_.end()) {
      throw std::runtime_error(std::format("Mesh does not support semantic: {}", toString(input.name)));
    }

    vertex_bindings.push_back({
        .buffer = vertex_buffer_,
        .offset = attr_it->offset,
    });
  }

  index_binding = {
      .buffer = index_buffer_,
      .offset = 0,
  };

  element_size = index_element_size_;
  index_count = index_count_;
}
} // namespace sft
