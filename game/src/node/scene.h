#pragma once

namespace sft {
class Node;
using NodePtr = std::shared_ptr<Node>;

struct ProcessGroup {
  i32 priority;

  u64 nodes_size{0};
  std::vector<NodePtr> nodes;

  bool dirty{false};
};

class Scene {
 public:
  void addNodeToUpdateGroup(NodePtr const& node);

  void removeNodeFromUpdateGroup(NodePtr const& node);

  void addNodeToPhysicsGroup(NodePtr const& node);

  void removeNodeFromPhysicsGroup(NodePtr const& node);

  void update(f64 delta_time);

  void physicsUpdate(f64 delta_time);

  void processDirtyGroups();

 private:
  u64 update_process_group_size_{0};
  u64 physics_process_group_size_{0};

  std::vector<std::unique_ptr<ProcessGroup>> update_process_groups_;
  std::vector<std::unique_ptr<ProcessGroup>> physics_process_groups_;

  bool update_process_group_dirty_{false};
  bool physics_process_group_dirty_{false};
};
} // namespace sft
