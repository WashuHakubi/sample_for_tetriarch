#include "node/node.h"
#include "node/scene.h"

namespace sft {
Node::Node(std::string name) : name_(std::move(name)) {}

void Node::addChild(NodePtr const& child) {
  std::string name = child->name();

  // Trim off '@...'
  if (auto idx = name.find('@'); idx != std::string::npos) {
    name.erase(idx);
  }

  // Make sure no other thread can modify this
  // Find a unique name for the child, if the name is not already unique, by appending @N where N is an integer that
  // makes the name unique.
  auto at_pos = std::string::npos;
  auto count = 1;
  while (children_.contains(name)) {
    if (at_pos == std::string::npos) {
      at_pos = name.size();
      name += "@";
    } else {
      name.erase(at_pos + 1);
    }

    name += std::to_string(count++);
  }

  // Update the name of the child
  child->name_ = std::move(name);

  auto [it, suc] = children_.emplace(child->name(), child);
  assert(suc && "Failed to add a node with a unique name!");

  // Update the parent to point to us
  it->second->parent_ = this;

  if (scene_) {
    child->setScene(scene_);
  }
}

NodePtr Node::findChild(std::string_view name) const noexcept {
  if (auto it = children_.find(name); it != children_.end()) {
    return it->second;
  }
  return nullptr;
}

NodePtr Node::parent() const noexcept {
  return parent_ ? parent_->shared_from_this() : nullptr;
}

void Node::removeChild(NodePtr const& child) {
  if (child->parent() != shared_from_this()) {
    SPDLOG_ERROR("Attempted to remove child {} from {}, which was not the parent", child->name(), name());
    return;
  }

  if (scene_) {
    // TODO: queue this on the scene
    // Tell the child it is leaving the scene.
    child->fireExitTree();
  }

  auto it = children_.find(child->name());
  assert(it != children_.end() && "Child node was not found in the parent");

  children_.erase(it);
  child->parent_ = nullptr;
}

void Node::setUpdates(bool enable) {
  if (enable == receiving_updates_) {
    return;
  }

  if (scene_) {
    if (receiving_updates_) {
      scene_->removeNodeFromUpdateGroup(shared_from_this());
    } else {
      scene_->addNodeToUpdateGroup(shared_from_this());
    }
  }

  receiving_updates_ = enable;
}

void Node::setUpdatePriority(i32 priority) {
  if (scene_ && receiving_updates_) {
    scene_->removeNodeFromUpdateGroup(shared_from_this());
  }

  update_priority_ = priority;

  if (scene_ && receiving_updates_) {
    scene_->addNodeToUpdateGroup(shared_from_this());
  }
}

void Node::setScene(Scene* scene) {
  if (scene_ == scene) {
    return;
  }

  if (scene_) {
    fireExitTree();
  }

  scene_ = scene;

  if (scene_) {
    fireEnterTree();

    // If we don't have a parent or our parent was already ready, then fire ready.
    if (!parent_ || parent_->ready_notified_) {
      fireReady();
    }
  }
}

void Node::fireEnterTree() {
  if (parent_) {
    scene_ = parent_->scene_;
    depth_ = parent_->depth_ + 1;
  } else {
    depth_ = 1;
  }

  enterTree();

  for (auto&& [_, child] : children_) {
    child->fireEnterTree();
  }
}

void Node::fireReady() {
  ready_notified_ = true;

  for (auto&& [_, child] : children_) {
    child->fireReady();
  }

  ready();
}

void Node::fireExitTree() {
  for (auto&& [_, child] : children_) {
    child->fireExitTree();
  }
  exitTree();

  ready_notified_ = false;
  scene_ = nullptr;
  depth_ = -1;
}

} // namespace sft
