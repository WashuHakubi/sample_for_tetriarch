#pragma once

#include <mutex>

namespace sft {
class Scene;

class Node;
using NodePtr = std::shared_ptr<Node>;

class Node : public std::enable_shared_from_this<Node> {
 public:
  Node(std::string name);

  virtual ~Node() = default;

  void addChild(NodePtr const& child);

  i32 depth() const noexcept { return depth_; }

  NodePtr findChild(std::string_view name) const noexcept;

  std::string const& name() const noexcept { return name_; }

  NodePtr parent() const noexcept;

  bool receiving_updates() const noexcept { return receiving_updates_; }

  void removeChild(NodePtr const& child);

  i32 updatePriority() const noexcept { return update_priority_; }

 protected:
  /// @brief Called when a node is added to a scene. This always fires on the parent before any of its children.
  virtual void enterTree() {};

  /// @brief Called after all nodes have been added to
  /// the scene, this is always called on the children
  /// before their parent.
  virtual void ready() {};

  /// @brief Called just before a node is removed from
  /// the scene. This is always called on child nodes
  /// before their parent.
  virtual void exitTree() {};

  virtual void update(f64 delta_time) {}

  virtual void physicsUpdate(f64 delta_time) {}

  void setUpdates(bool enable);

  void setUpdatePriority(i32 priority);

 private:
  friend class Scene;

  void setScene(Scene* scene);

  /// @brief Fires enterTree() on this node, and then
  /// recursively fires enterTree() on child nodes.
  void fireEnterTree();

  /// @brief recursively fires ready() on child nodes,
  /// and then fires ready() on this node.
  void fireReady();

  /// @brief recursively fires exitTree() on child
  /// nodes, and then fires exitTree() on this node.
  void fireExitTree();

 private:
  std::string name_;
  Scene* scene_{nullptr};

  Node* parent_{nullptr};
  std::unordered_map<std::string_view, NodePtr> children_;

  i32 depth_{-1};
  i32 update_priority_{0};

  bool ready_notified_{false};
  bool receiving_updates_{false};
};
} // namespace sft
