#define SDL_MAIN_USE_CALLBACKS 1 // NOLINT
#include "SDL3/SDL_main.h"
#include "SDL3/SDL.h"

#include "core/app_callbacks.h"

auto SDL_AppInit(void** appstate, int argc, char** argv) -> SDL_AppResult {
  auto state = sft::createAppCallbacks();

  if (!SDL_InitSubSystem(SDL_INIT_EVENTS | SDL_INIT_VIDEO | SDL_INIT_AUDIO)) {
    SPDLOG_CRITICAL("Failed to initialize SDL subsystems: {}", SDL_GetError());
    return SDL_APP_FAILURE;
  }

  if (!state->initialize(argc, argv)) {
    return SDL_APP_FAILURE;
  }

  *appstate = state.release();
  return SDL_APP_CONTINUE;
}

auto SDL_AppIterate(void* appstate) -> SDL_AppResult {
  auto* state = static_cast<sft::AppCallbacks*>(appstate);
  assert(state);

  // update returns true to continue, false to stop
  return state->update() ? SDL_APP_CONTINUE : SDL_APP_SUCCESS;
}

auto SDL_AppEvent(void* appstate, SDL_Event* event) -> SDL_AppResult {
  auto* state = static_cast<sft::AppCallbacks*>(appstate);
  assert(state);

  // handleEvent returns true to continue, false to stop
  return state->handleEvent(event) ? SDL_APP_CONTINUE : SDL_APP_SUCCESS;
}

void SDL_AppQuit(
    void* appstate,
    SDL_AppResult /*result*/
) {
  // Wrap the state up in a unique_ptr to ensure it gets deleted when we return.
  auto state = std::unique_ptr<sft::AppCallbacks>{static_cast<sft::AppCallbacks*>(appstate)};

  // Inform the callback that we're quitting. This lets it perform any non-destructor bsaed cleanup.
  state->quit();
}
